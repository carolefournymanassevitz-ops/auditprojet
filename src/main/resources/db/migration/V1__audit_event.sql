-- Journal des actions sensibles.
-- §7.3 : schéma PORTAL, modèle physique (table AUDIT_EVENT).
-- ST-09 : journal d'audit en ajout seul : qui, quoi, quand (UTC), sur quoi, résultat.
-- §7.4 : règles physiques compatibles avec Oracle 19c : clé IDENTITY, JSON en CLOB contrôlé par IS JSON (type JSON natif seulement en 21c).
-- L'horodatage est posé par la base, en UTC, pour ne pas dépendre du fuseau de la JVM.
CREATE TABLE AUDIT_EVENT (
    EVENT_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OCCURRED_AT     TIMESTAMP(3) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    API_NAME        VARCHAR2(20)  NOT NULL,
    DESIGNATION     VARCHAR2(30)  NOT NULL,
    ACTOR_SUB       VARCHAR2(64)  NOT NULL,
    ACTOR_NAME      VARCHAR2(100),
    ACTION          VARCHAR2(50)  NOT NULL,
    TARGET_TYPE     VARCHAR2(30)  NOT NULL,
    TARGET_ID       VARCHAR2(64)  NOT NULL,
    TARGET_PRM      VARCHAR2(20),
    OUTCOME         VARCHAR2(10)  NOT NULL,
    CORRELATION_ID  VARCHAR2(36)  NOT NULL,
    TRACE_ID        VARCHAR2(32),
    DETAILS         CLOB,
    CONSTRAINT CK_AUDIT_EVENT_OUTCOME CHECK (OUTCOME IN ('DEMANDE', 'SUCCES', 'ECHEC', 'INCONNU')),
    CONSTRAINT CK_AUDIT_EVENT_DETAILS CHECK (DETAILS IS JSON)
);

CREATE INDEX IX_AUDIT_EVENT_DESIGNATION ON AUDIT_EVENT (DESIGNATION, OCCURRED_AT);
CREATE INDEX IX_AUDIT_EVENT_PRM ON AUDIT_EVENT (TARGET_PRM);
CREATE INDEX IX_AUDIT_EVENT_CORRELATION ON AUDIT_EVENT (CORRELATION_ID);
